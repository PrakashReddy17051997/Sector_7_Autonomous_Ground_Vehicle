#!/usr/bin/env python3
"""Segment map for LiDAR + IMU localisation along the taught route (teach & repeat).

    python3 make_segments.py log_009.csv                       # writes ../cas_box/RouteMap.h
    python3 make_segments.py log_009.csv --check log_011.csv   # + replay a repeat run against the map

INPUT: a teaching log decoded by analyze_log.py (CSV) with Mark presses. The legs (segments) and how
each one ends come from make_legs.py (from the Mark TAGS of a v2 log, else its hand-written PLAN), so
RouteMap.h and kRoute in RouteFollow.cpp describe the same legs - paste the kRoute table that
make_legs.py prints after every new teaching run (the box checks that the leg counts agree).

WHAT THE MAP HOLDS (per leg, all LiDAR scans 90 x 4 deg, stored in 4 cm steps = 90 bytes each)
  end keyframe      the scan at the taught END of the leg (facade end, ramp entry, corner ...).
                    On the box the leg may only end where the live scan looks like this one
                    (RouteLocalizer: dip of the end-scan cost) -> no early exit from corridors,
                    no turning before the ramp.
  route keyframes   one scan every 2 m of the taught path, tagged with the leg and the fraction of
                    the leg's taught effort. Used to tell STATIC things (walls, railings, ramp edges,
                    seen in the teaching run) from NEW obstacles (people, bikes): only new ones make
                    the rover stop and avoid.
  Size: (10 + ~45) x 90 B = ~5 kB of flash.

--check REPEAT.csv  replays the repeat log leg by leg with the box rules and prints, for every leg,
  where the leg would have ended (route position from GPS, shifted onto the teaching track in a
  +-45 s window - itself only good to ~3-5 m) for the old rule and the new combined rule, and how
  many "something ahead" events were static vs new. Use it after every field test.
"""
import argparse
import datetime
import math
import sys
import warnings
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).parent))
import lidarmatch as lm  # noqa: E402
import make_legs as ML  # noqa: E402
import navlib as nl  # noqa: E402

warnings.simplefilter("ignore")
KEY_STEP_M = 2.0


def load(path):
    A = pd.read_csv(path)
    lid = [c for c in A.columns if c.startswith("lidar_")]
    S = A[lid].values.astype(float)
    return A[[c for c in A.columns if not c.startswith("lidar_")]].copy(), S


def path_length(A):
    """distance along the driven path (m) from smoothed GPS: the GPS offset cancels inside one run"""
    ch = np.r_[True, (np.diff(A.lat) != 0) | (np.diff(A.lon) != 0)] & (A.gps_fix == 1)
    g = A[ch]
    k = np.ones(5) / 5
    pad = lambda x: np.r_[[x.iloc[0]] * 2, x, [x.iloc[-1]] * 2]
    e, n = np.convolve(pad(g.east_m), k, "valid"), np.convolve(pad(g.north_m), k, "valid")
    s = np.r_[0, np.cumsum(np.hypot(np.diff(e), np.diff(n)))]
    return np.interp(A.t_s, g.t_s, s)


def build(A, S, legs):
    s = path_length(A)
    vf = ((A.out_l + A.out_r) / 2).clip(lower=0).values
    end_keys, keys, info = [], [], []
    for k, L in enumerate(legs):
        end_keys.append(lm.keyframe(S, L["i1"]))
        i0 = legs[k - 1]["i1"] + 1 if k else 0
        eff = np.cumsum(vf[i0:L["i1"] + 1]) * 0.25
        nxt = s[i0]
        for i in range(i0, L["i1"] + 1):
            if s[i] >= nxt:
                keys.append(lm.keyframe(S, i))
                info.append((k, min(255, int(round(100 * eff[i - i0] / max(L["eff"], 1e-3))))))
                nxt += KEY_STEP_M
    return np.array(end_keys), np.array(keys), info, s


def write_header(path, legs, end_keys, keys, info, src):
    q = lambda a: ", ".join(str(int(v)) for v in lm.quantise(a))
    with open(path, "w") as f:
        f.write("#pragma once\n")
        f.write(f"// RouteMap - LiDAR keyframes of the taught route. GENERATED by tools/make_segments.py from {src}\n")
        f.write(f"// on {datetime.date.today()}. Do not edit by hand: re-run the tool after a new teaching run\n")
        f.write("// (and make_legs.py for kRoute in RouteFollow.cpp - both use the same PLAN).\n")
        f.write("// Scans: 90 points x 4 deg (0 = front, clockwise), value * 4 = cm, 0 = no return.\n")
        f.write("#include <stdint.h>\n\nnamespace RouteMap {\n")
        f.write(f"static const uint8_t kLegs = {len(legs)};\n")
        f.write(f"static const uint8_t kKeys = {len(keys)};\n")
        f.write("struct KeyInfo { uint8_t leg; uint8_t frac100; };  // leg index, % of the leg's taught effort\n\n")
        f.write("// scan at the taught END of each leg\nstatic const uint8_t kEnd[kLegs][90] = {\n")
        for k, (L, e) in enumerate(zip(legs, end_keys)):
            f.write(f"  {{{q(e)}}},  // {k + 1}: {L['name']}\n")
        f.write("};\n\n// route keyframes every 2 m of the taught path (static scene for the obstacle check)\n")
        f.write("static const KeyInfo kKeyInfo[kKeys] = {\n  ")
        f.write(", ".join(f"{{{a}, {b}}}" for a, b in info))
        f.write("\n};\nstatic const uint8_t kKey[kKeys][90] = {\n")
        for (a, b), kk in zip(info, keys):
            f.write(f"  {{{q(kk)}}},  // leg {a + 1}, {b} %\n")
        f.write("};\n}  // namespace RouteMap\n")


# ------------------------------------------------------------------------------------------ check
def check(A, S, sA, legs, end_keys, keys, info, rep_path):
    B, SB = load(rep_path)
    ends = [sA[L["i1"]] for L in legs]
    EK = [lm.dequantise(lm.quantise(e)) for e in end_keys]          # exactly what the box has
    KK = [lm.dequantise(lm.quantise(k)) for k in keys]
    vf = ((B.out_l + B.out_r) / 2).clip(lower=0).values
    kc = 111194.93
    c0 = math.cos(math.radians(A.lat.iloc[0]))
    PA = np.c_[(A.lon - A.lon.iloc[0]) * kc * c0, (A.lat - A.lat.iloc[0]) * kc][::2]
    sA2 = sA[::2]
    PB = np.c_[(B.lon - A.lon.iloc[0]) * kc * c0, (B.lat - A.lat.iloc[0]) * kc]
    fixB = np.r_[True, (np.diff(B.lat) != 0) | (np.diff(B.lon) != 0)] & (B.gps_fix == 1)

    def route_pos(i, win=45):  # GPS of the repeat run, shifted onto the teaching track (+-45 s window)
        m = fixB & (np.abs(B.t_s - B.t_s.iloc[i]) <= win)
        X = PB[m][::2]
        off = np.zeros(2)
        for _ in range(12):
            j = [np.argmin(np.hypot(*(PA - x - off).T)) for x in X]
            off += np.mean(PA[j] - (X + off), axis=0)
        return sA2[np.argmin(np.hypot(*(PA - (PB[i] + off)).T))]

    def wall(i, side):
        w = nl.measure(SB[i], side)
        return (w["ok"] and w["pts"] >= 6), w["d"]

    def run(rule):
        res, timeline = [], np.full(len(B), -1)
        i = int(np.argmax(vf > 0.05))
        for k, L in enumerate(legs):
            eff = 0.0; seen = 0; lostN = foundN = 0; fr = []; det = lm.EndDetector(); done = None
            side = -1 if L["side"] == "L" else 1
            i_start = i
            while i < len(B) - 1:
                eff += vf[i] * 0.25
                frac = eff / L["eff"]
                gate = frac >= L["gate"]
                if L["end"] == "LOST":
                    ok, _ = wall(i, side); seen |= ok; lostN = 0 if ok else lostN + 1
                    ev = gate and seen and lostN >= 6
                elif L["end"] in ("FOUND_L", "FOUND_R"):
                    ok, d = wall(i, -1 if L["end"] == "FOUND_L" else 1)
                    foundN = foundN + 1 if (ok and d < L["arg"]) else 0
                    ev = gate and foundN >= 4
                elif L["end"] == "FRONT":
                    fr.append(nl.corridor(SB[i], 0, look=3.0, minr=0.25))
                    ev = gate and len(fr) >= 4 and np.median(fr[-4:]) < L["arg"]
                else:
                    ev = frac >= 0.97
                if frac >= 0.3 and i % 2 == 0:
                    det.feed(lm.end_cost(SB[i], EK[k]), gate, i)
                if rule == "old":
                    lim = (2.5 if (L["end"] == "LOST" and lostN < 8) else 1.3) * L["eff"] + 2
                    if ev or eff > lim: done = i; break
                else:
                    if ev and det.looks_like_end(): done = i; break
                    if det.dip(): done = i; break   # the box ends the leg when it sees the dip (~1.5 s after the minimum)
                    if eff > 1.8 * L["eff"] + 2: done = i; break
                i += 1
            if done is None: done = len(B) - 1
            timeline[i_start:done + 1] = k
            res.append(route_pos(done) - ends[k])
            i = done + 1
        return np.array(res), timeline

    old, _ = run("old")
    new, tl = run("new")
    print(f"\nreplay of {Path(rep_path).name} against the map (error where the leg ends, m; - = too early)")
    w = max(19, max(len(L["name"]) for L in legs))
    print(f"{'leg':<{w + 3}} {'old rule':>9} {'new rule':>9}")
    for k, L in enumerate(legs):
        print(f"{k + 1:>2} {L['name']:<{w}} {old[k]:+9.1f} {new[k]:+9.1f}")
    print(f"{'median |error|':<{w + 3}} {np.median(np.abs(old)):9.1f} {np.median(np.abs(new)):9.1f}")
    print(f"{'max |error|':<{w + 3}} {np.max(np.abs(old)):9.1f} {np.max(np.abs(new)):9.1f}")
    print("(reference = GPS shifted onto the teaching track, itself good to ~3-5 m)")

    # static vs new obstacles (keys of the current and the next leg, like the box)
    raw = new_ev = 0; pr = pn = False
    for i in range(len(B)):
        k = tl[i]
        if k < 0: continue
        bins = lm.ahead_bins(SB[i])
        r = len(bins) >= 1
        ks = [KK[j] for j, (lg, _) in enumerate(info) if lg in (k, k + 1)]
        n = r and len(lm.new_points(SB[i], bins, ks)) >= 2
        raw += r and not pr; new_ev += n and not pn; pr, pn = r, n
    print(f"something ahead within 0.7 m: {raw} events, of these NEW (not in the taught scans): {new_ev}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("teach", help="teaching log CSV (analyze_log.py) with Mark presses")
    ap.add_argument("--out", default=str(Path(__file__).resolve().parent.parent / "cas_box" / "RouteMap.h"))
    ap.add_argument("--check", metavar="REPEAT_CSV", help="replay a repeat run against the map")
    a = ap.parse_args()
    A, S = load(a.teach)
    A2, S2 = ML.load(a.teach)
    legs, _ = ML.build(A2, S2)
    end_keys, keys, info, sA = build(A, S, legs)
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    write_header(a.out, legs, end_keys, keys, info, Path(a.teach).name)
    print(f"{len(legs)} legs, {len(keys)} route keyframes, taught path {sA[-1]:.1f} m "
          f"-> {a.out} ({(len(legs) + len(keys)) * 90 + 2 * len(keys)} bytes of map data)")
    for k, L in enumerate(legs):
        n = sum(1 for lg, _ in info if lg == k)
        print(f"  leg {k + 1:>2} {L['name']:<28} ends at {sA[L['i1']]:5.1f} m, end={L['end']:<8} {n} keyframes")
    if a.check:
        check(A, S, sA, legs, end_keys, keys, info, a.check)


if __name__ == "__main__":
    main()
