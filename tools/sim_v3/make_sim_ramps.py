#!/usr/bin/env python3
"""make_sim_ramps.py - pitch profile of the teaching run for the simulator (tools/sim_v3/sim_ramps.h).

Per leg (kRoute order, Mark ranges of landmark_scan.LEG_MARKS) and per metre of the taught path: the median IMU pitch
while driving (deg). The sim sets the IMU pitch from it (so the firmware's ramp mode and tilt gates switch as on the
real route) and clears map cells near the path where the teaching LiDAR plane was tilted (it hit the ramp surface).
    python3 tools/sim_v3/make_sim_ramps.py cas_box_log/log_027.csv
"""
import csv, re, sys, os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from landmark_scan import LEG_MARKS

here = os.path.dirname(os.path.abspath(__file__))
h = open(os.path.join(here, "../../cas_box_v3/LocalPath.h")).read()
sEnd = [float(m) for m in re.findall(r"\{\d+, kPath\d+, ([\d.]+)f", h)]
rows = list(csv.DictReader(open(sys.argv[1])))
out = []
for k, (m0, m1) in enumerate(LEG_MARKS):
    mov = [float(r["pitch_deg"]) for r in rows if m0 <= int(float(r["mark"] or 0)) < m1
           and 0.5 * (float(r["cmd_l"] or 0) + float(r["cmd_r"] or 0)) > 0.05]
    n = len(mov)
    prof = []
    for m in range(int(sEnd[k]) + 1):
        seg = [mov[i] for i in range(n) if n > 1 and int(sEnd[k] * i / (n - 1)) == m]
        prof.append(sorted(seg)[len(seg) // 2] if seg else (prof[-1] if prof else 0.0))
    out.append(prof)
with open(os.path.join(here, "sim_ramps.h"), "w") as f:
    f.write("#pragma once\n// GENERATED by make_sim_ramps.py from %s: median IMU pitch (deg) per metre of the taught\n"
            "// path of each leg while driving. The sim sets the IMU pitch from it.\n" % os.path.basename(sys.argv[1]))
    for k, p in enumerate(out):
        f.write("static const float kSimPitch%d[] = {%s};\n" % (k, ", ".join("%.1ff" % v for v in p)))
    f.write("struct SimPitch { const float* p; int n; };\nstatic const SimPitch kSimPitch[] = {\n")
    for k, p in enumerate(out):
        f.write("  {kSimPitch%d, %d},\n" % (k, len(p)))
    f.write("};\n")
print("written sim_ramps.h (%d legs)" % len(out))
